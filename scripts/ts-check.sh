#!/usr/bin/env bash
# SPDX-License-Identifier: MIT OR Apache-2.0
# Build the TypeScript package and test what it would publish:
#
# 0. the only unsafe-code allowances in the WebAssembly crate are on its
#    exported functions;
# 1. build the module (wasm32, no imports), embed it, compile with the pinned
#    TypeScript (npm ci from the committed lockfile), and npm pack;
# 2. install the tarball into a throwaway project and run the API tests and
#    the canonical-json/v0 corpus against it (node:test, no skips);
# 3. its corpus result lines equal Rust's, byte for byte;
# 4. its differential driver equals Rust's on the crosscheck seeds.
#
# Prints the packed tarball path on success when TS_CHECK_KEEP=<dir> names a
# directory to copy it into.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
python="${PYTHON:-python3}"
seeds="${CROSSCHECK_SEEDS:-20261022 20261023}"
count="${CROSSCHECK_COUNT:-5000}"
pkg="${root}/bindings/typescript"
work="$(mktemp -d "${TMPDIR:-/tmp}/canonprims-ts.XXXXXX")"
trap 'rm -rf "${work}"' EXIT
cd "${root}"

for license in LICENSE-MIT LICENSE-APACHE; do
  cmp -s "${license}" "${pkg}/${license}" ||
    { echo "ts-check: bindings/typescript/${license} differs from ${license}" >&2; exit 1; }
done
# Each `#[allow(unsafe_code)]` must sit directly above `#[no_mangle]`.
"${python}" -I - "${pkg}/src/lib.rs" <<'PY'
import sys
lines = open(sys.argv[1], encoding="utf-8").read().splitlines()
bad = [i + 1 for i, l in enumerate(lines)
       if "unsafe" in l and not l.lstrip().startswith(("//", "///", "//!"))
       and not (l.strip() == "#[allow(unsafe_code)]" and i + 1 < len(lines) and lines[i + 1].strip() == "#[no_mangle]")]
if bad:
    sys.exit(f"ts-check: unsafe outside an export allowance at lines {bad}")
PY

target_dir="${CARGO_TARGET_DIR:-${root}/target}/wasm"
# Panic locations embed source paths; map the checkout, the Cargo home and
# the rustup home (a toolchain with rust-src names its own library sources)
# to fixed names so the module carries no build-host path.
physical_root="$(pwd -P)"
cargo_home="${CARGO_HOME:-${HOME}/.cargo}"
rustup_home="${RUSTUP_HOME:-${HOME}/.rustup}"
CARGO_TARGET_DIR="${target_dir}" \
  RUSTFLAGS="--remap-path-prefix=${physical_root}=/canonprims --remap-path-prefix=${cargo_home}=/cargo --remap-path-prefix=${rustup_home}=/rustup" \
  cargo build --quiet --locked --release \
  --manifest-path "${pkg}/Cargo.toml" --target wasm32-unknown-unknown
module="${target_dir}/wasm32-unknown-unknown/release/canonprims_wasm.wasm"
if LC_ALL=C grep -aqF -e "${physical_root}" -e "${cargo_home}" -e "${rustup_home}" -e "${HOME}" "${module}"; then
  echo "ts-check: the module embeds a build-host path" >&2
  exit 1
fi
node --input-type=module - "${module}" <<'JS'
import { readFileSync } from "node:fs";
const m = new WebAssembly.Module(readFileSync(process.argv[2]));
const imports = WebAssembly.Module.imports(m);
if (imports.length) { console.error("ts-check: the module has imports:", imports); process.exit(1); }
JS
# The module is embedded as base64 so the package loads with no file or
# network read, in every runtime. The generated file is not tracked.
{
  echo "// Generated by scripts/ts-check.sh from the canonprims-wasm module. Do not edit."
  printf 'export const WASM_BASE64: string =\n  "%s";\n' "$(base64 < "${module}" | tr -d '\n')"
} > "${pkg}/ts/wasm.ts"

(cd "${pkg}" && npm ci --ignore-scripts --no-audit --no-fund --silent && rm -rf dist && node_modules/.bin/tsc -p tsconfig.json)
version="$(tr -d ' \t\r\n' < VERSION)"
tarball="$(cd "${pkg}" && npm pack --silent --pack-destination "${work}")"
tarball="${work}/${tarball##*/}"
[ "${tarball##*/}" = "3leaps-canonprims-${version}.tgz" ] || { echo "ts-check: unexpected tarball ${tarball##*/}" >&2; exit 1; }
listed="$(tar -tzf "${tarball}" | LC_ALL=C sort | tr '\n' ' ')"
want="package/LICENSE-APACHE package/LICENSE-MIT package/README.md package/dist/index.d.ts package/dist/index.js package/dist/wasm.d.ts package/dist/wasm.js package/package.json "
[ "${listed}" = "${want}" ] || { echo "ts-check: tarball contents differ: ${listed}" >&2; exit 1; }

# A consumer project: the tarball, nothing else, no registry access.
mkdir "${work}/consumer"
cp -R "${pkg}/test" "${work}/consumer/test"
printf '{"name":"consumer","private":true,"type":"module"}\n' > "${work}/consumer/package.json"
(cd "${work}/consumer" && npm install --offline --ignore-scripts --no-audit --no-fund --silent "${tarball}")

(cd "${work}/consumer" && CANONPRIMS_CORPUS_DIR="${root}/conformance/canonical-json/v0" \
  CANONPRIMS_RESULTS_OUT="${work}/ts.results" CANONPRIMS_VERSION="${version}" \
  node --test --test-reporter=tap test/api.test.mjs test/corpus.test.mjs > "${work}/test.tap" 2>&1) ||
  { cat "${work}/test.tap" >&2; exit 1; }
# Every test must pass: none failed, cancelled, skipped or todo, and the
# files did run (the API and corpus tests number more than 10).
"${python}" -I - "${work}/test.tap" <<'PY' ||
import re, sys
text = open(sys.argv[1], encoding="utf-8").read()
counts = {k: int(v) for k, v in re.findall(r"^# (tests|pass|fail|cancelled|skipped|todo) (\d+)$", text, re.M)}
ok = (len(counts) == 6 and counts["pass"] == counts["tests"] and counts["tests"] > 10
      and not any(counts[k] for k in ("fail", "cancelled", "skipped", "todo")))
sys.exit(0 if ok else f"summary {counts}")
PY
  { cat "${work}/test.tap" >&2; echo "ts-check: tests failed, skipped or todo" >&2; exit 1; }

CANONPRIMS_RESULTS_OUT="${work}/rust.results" cargo test --quiet --locked -p canonprims-json --test corpus corpus >/dev/null
if [ ! -s "${work}/ts.results" ] || ! cmp -s "${work}/rust.results" "${work}/ts.results"; then
  echo "ts-check: corpus results differ (rust vs typescript):" >&2
  diff "${work}/rust.results" "${work}/ts.results" | head -20 >&2 || true
  exit 1
fi
echo "ts-check: corpus agrees with Rust ($(wc -l < "${work}/ts.results" | tr -d ' ') cases)" >&2

rust_driver="$(cargo build --quiet --locked --release -p canonprims-json --example canon-diff --message-format=json \
  | "${python}" -I -c 'import json,sys
for line in sys.stdin:
    m = json.loads(line)
    if m.get("reason") == "compiler-artifact" and m.get("target", {}).get("name") == "canon-diff" and m.get("executable"):
        print(m["executable"])')"
for seed in ${seeds}; do
  "${python}" -I scripts/crosscheck-gen.py "${seed}" "${count}" > "${work}/in.${seed}"
  "${rust_driver}" < "${work}/in.${seed}" > "${work}/rust.${seed}"
  (cd "${work}/consumer" && node test/canon-diff.mjs < "${work}/in.${seed}" > "${work}/ts.${seed}")
  if ! cmp -s "${work}/rust.${seed}" "${work}/ts.${seed}"; then
    echo "ts-check: drivers differ for seed ${seed} (rust vs typescript)" >&2
    exit 1
  fi
  echo "ts-check: seed ${seed} agrees with Rust (${count} inputs)" >&2
done
if [ -n "${TS_CHECK_KEEP:-}" ]; then cp "${tarball}" "${TS_CHECK_KEEP}/"; fi
echo "[ok] ts-check"
